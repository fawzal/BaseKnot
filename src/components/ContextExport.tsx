import { useState, useTransition } from 'react';
import { UXTraceabilityThread } from '@/types/database';
import { Terminal, Copy, Check, Download, Sparkles, RefreshCw } from 'lucide-react';

interface ContextExportProps {
  onFetchTraceability: () => Promise<UXTraceabilityThread[]>;
}

export function ContextExport({ onFetchTraceability }: ContextExportProps) {
  const [threads, setThreads] = useState<UXTraceabilityThread[] | null>(null);
  const [markdownPrompt, setMarkdownPrompt] = useState<string>('');
  const [isCopied, setIsCopied] = useState(false);
  const [isPending, startTransition] = useTransition();

  const generatePrompt = async () => {
    startTransition(async () => {
      const data = await onFetchTraceability();
      setThreads(data);

      const timestamp = new Date().toISOString();
      let md = `# SYSTEM INSTRUCTION: UX LOGIC THREAD — HIGH-FIDELITY IMPLEMENTATION\n`;
      md += `> Generated by UX Logic Thread Engine at ${timestamp}\n`;
      md += `> Source of Truth: Relational UX Traceability Mapping\n\n`;
      md += `## 1. Context & North Star\n`;
      md += `You are an elite Frontend & UI Systems Engineer. Every visual element, placement, and token below has a direct relational lineage from real user research insights. Follow these relational constraints strictly.\n\n`;

      if (data.length === 0) {
        md += `*(No traceability threads available. Populate Research Hub, Sitemap, and UI Tokens first.)*\n`;
      } else {
        md += `## 2. Relational Logic Threads (Research to UI Tokens)\n\n`;
        data.forEach((thread, rIndex) => {
          md += `### Thread ${rIndex + 1}: [Research Insight #${thread.research.id.slice(-4)}]\n`;
          md += `**User Problem / Observation:**\n> "${thread.research.insight_text}"\n\n`;

          if (thread.features.length === 0) {
            md += `- *No feature linked yet.*\n\n`;
          } else {
            md += `#### Linked Features & Architectural Placement:\n`;
            thread.features.forEach((featWrap, fIndex) => {
              const feat = featWrap.feature;
              md += `\n**Feature ${rIndex + 1}.${fIndex + 1}: ${feat.feature_name}**\n`;
              if (feat.description) {
                md += `- *Justification / UX Rationale:* ${feat.description}\n`;
              }

              if (featWrap.sitemapNodes.length === 0) {
                md += `- *Status:* Not yet placed on Sitemap.\n`;
              } else {
                md += `- *Information Architecture (Sitemap):*\n`;
                featWrap.sitemapNodes.forEach((nodeWrap) => {
                  const node = nodeWrap.node;
                  md += `  - **Page:** \`${node.page_name}\` | **Hierarchy Zone:** \`${node.hierarchy_level}\`\n`;

                  if (nodeWrap.tokens.length === 0) {
                    md += `    - *Tokens:* (Default surface styling)\n`;
                  } else {
                    md += `    - *Design Tokens & Components:*\n`;
                    nodeWrap.tokens.forEach((tok) => {
                      md += `      - **Component:** \`${tok.component_type}\`\n`;
                      md += `        - Token Rules: \`${tok.design_token}\`\n`;
                    });
                  }
                });
              }
            });
            md += `\n---\n\n`;
          }
        });

        md += `## 3. Implementation Rules for Claude / Figma MCP / Cursor\n`;
        md += `1. **Zero Drift:** Do NOT invent components or modify hierarchy placement without checking research lineage.\n`;
        md += `2. **Tokens Enforcement:** Apply the specified design token classes strictly.\n`;
        md += `3. **Editorial Minimalism:** Preserve dark theme background \`#0B0B0B\`, surface \`#141414\`, border \`#242424\`, and subtle accents.\n`;
      }

      setMarkdownPrompt(md);
    });
  };

  const handleCopy = async () => {
    if (!markdownPrompt) return;
    try {
      await navigator.clipboard.writeText(markdownPrompt);
      setIsCopied(true);
      setTimeout(() => setIsCopied(false), 2000);
    } catch (e) {
      console.warn('Copy failed:', e);
    }
  };

  const handleDownload = () => {
    if (!markdownPrompt) return;
    const blob = new Blob([markdownPrompt], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `ux-logic-thread-context-${Date.now()}.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      {/* Top Banner */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 p-4 bg-surface rounded-xl border border-border">
        <div>
          <div className="flex items-center gap-2">
            <Terminal className="w-4 h-4 text-accent" />
            <h2 className="text-sm font-semibold text-foreground">
              Modul 4: Context Export Engine (Prompt Generator)
            </h2>
          </div>
          <p className="text-xs text-foreground-muted mt-1">
            Kueri seluruh data relasional hulu ke hilir menjadi Markdown System Prompt siap pakai untuk Claude (via Figma MCP) atau Cursor.
          </p>
        </div>

        <button
          onClick={generatePrompt}
          disabled={isPending}
          className="px-4 py-2 bg-accent hover:bg-accent-hover disabled:opacity-50 text-white rounded-lg text-xs font-semibold flex items-center gap-2 transition-all shadow-glow-sm self-start sm:self-auto"
        >
          {isPending ? (
            <RefreshCw className="w-3.5 h-3.5 animate-spin" />
          ) : (
            <Sparkles className="w-3.5 h-3.5" />
          )}
          <span>{markdownPrompt ? 'Regenerate Context' : 'Generate Relational Prompt'}</span>
        </button>
      </div>

      {markdownPrompt ? (
        <div className="space-y-3">
          {/* Action bar */}
          <div className="flex items-center justify-between bg-surface px-4 py-2.5 rounded-lg border border-border">
            <div className="flex items-center gap-2">
              <span className="w-2 h-2 rounded-full bg-emerald-400" />
              <span className="text-xs font-mono text-foreground-muted">
                RELATIONAL PROMPT READY ({threads?.length || 0} THREADS)
              </span>
            </div>

            <div className="flex items-center gap-2">
              <button
                onClick={handleCopy}
                className="px-3 py-1.5 rounded bg-surface-elevated hover:bg-surface-hover border border-border text-foreground text-xs font-medium flex items-center gap-1.5 transition-colors"
              >
                {isCopied ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-emerald-400" />
                    <span className="text-emerald-400">Copied!</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5 text-accent" />
                    <span>Copy to Clipboard</span>
                  </>
                )}
              </button>

              <button
                onClick={handleDownload}
                className="px-3 py-1.5 rounded bg-surface-elevated hover:bg-surface-hover border border-border text-foreground-muted hover:text-foreground text-xs font-medium flex items-center gap-1.5 transition-colors"
              >
                <Download className="w-3.5 h-3.5" />
                <span className="hidden sm:inline">Download .md</span>
              </button>
            </div>
          </div>

          {/* Prompt Content Preview */}
          <div className="relative bg-[#0E0E0E] rounded-xl border border-border p-4 overflow-hidden">
            <pre className="font-mono text-xs text-foreground-muted leading-relaxed whitespace-pre-wrap max-h-[550px] overflow-y-auto selection:bg-accent/40 selection:text-white">
              {markdownPrompt}
            </pre>
          </div>
        </div>
      ) : (
        <div className="p-12 text-center border border-dashed border-border rounded-xl bg-surface/30 space-y-3">
          <Terminal className="w-8 h-8 text-accent/60 mx-auto" />
          <div className="space-y-1">
            <h3 className="text-sm font-semibold text-foreground">Siap Mengompilasi Benang Merah Logika</h3>
            <p className="text-xs text-foreground-muted max-w-md mx-auto">
              Klik tombol &quot;Generate Relational Prompt&quot; di atas untuk menarik seluruh Foreign Key dari tabel riset, fitur, sitemap, dan design tokens ke satu prompt Markdown.
            </p>
          </div>
          <button
            onClick={generatePrompt}
            className="px-4 py-2 bg-surface-elevated hover:bg-surface-hover border border-border text-foreground text-xs rounded-lg font-medium inline-flex items-center gap-1.5"
          >
            <Sparkles className="w-3.5 h-3.5 text-accent" />
            <span>Generate Context Sekarang</span>
          </button>
        </div>
      )}
    </div>
  );
}
